print('Ты просыпаешься в тёмной комнате. Перед тобой две двери: левая и правая.')
print('Куда пойдёшь? (лево/право)')
choice1 = input()

if choice1 == 'лево':
    print('Ты открываешь левую дверь и видишь лестницу вниз и вверх.')
    print('Куда пойдёшь? (вниз/вверх)')
    choice2 = input()
    if choice2 == 'вниз':
        print('Внизу тебя ждёт сундук с сокровищами. Ты победил!')
    elif choice2 == 'вверх':
        print('Наверху оказался выход на крышу. Ты свободен!')
    else:
        print('Ты замешкался и провалился в пропасть. Конец.')
elif choice1 == 'право':
    print('За правой дверью стоит огромный страж.')
    print('Что сделаешь? (атаковать/убежать)')
    choice2 = input()
    if choice2 == 'атаковать':
        print('Страж оказался слишком силён. Ты проиграл.')
    elif choice2 == 'убежать':
        print('Ты успешно сбежал и нашёл тайный выход. Победа!')
    else:
        print('Страж заметил тебя и схватил. Конец.')
else:
    print('Ты остаёшься на месте и ничего не происходит. Скучный конец.')